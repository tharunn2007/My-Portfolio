export const catGeometry = (cols = 80, rows = 40) => ({
  width: Math.min(cols - 2, Math.max(...CAT.map((line) => [...line].length))),
  height: Math.min(31, Math.max(10, rows - 7)),
});
export const renderCatFrame = (phase = 0, _unused = 0, geometry = catGeometry()) => {
  const width = Math.max(8, geometry.width);
  const sourceWidth = Math.max(...CAT.map((line) => [...line].length));
  return Array.from({ length: geometry.height }, (_, row) => {
    const sourceRow = Math.min(CAT.length - 1, Math.floor((row * CAT.length) / geometry.height));
    const chars = [...CAT[sourceRow]];
    let line = "";
    for (let col = 0; col < width; col++) {
      const sourceCol = Math.floor((col * sourceWidth) / width);
      const eye =
        sourceRow >= 12 &&
        sourceRow <= 14 &&
        ((sourceCol >= 14 && sourceCol <= 16) || (sourceCol >= 26 && sourceCol <= 28));
      const sparkle = eye && Math.sin(phase * 1.8) > 0.85;
      line += eye
        ? `\x1b[38;2;${sparkle ? "224;255;240" : "115;207;177"}m${sparkle && sourceRow === 13 ? "✧" : chars[sourceCol] || " "}\x1b[0m`
        : chars[sourceCol] || " ";
    }
    return `\x1b[38;2;192;205;214m${line}\x1b[0m`;
  });
};

// The welcome pill — GitHub-green accent to match the contribution heatmap.
export const bannerWelcomeLines = (message = "Welcome to Tharunn's portfolio!") => {
  const inner = ` ✳ ${message} `;
  return [
    ansi(BANNER_COLORS.accent, `╭${"─".repeat(inner.length)}╮`),
    `${ansi(BANNER_COLORS.accent, "│")}\x1b[1m${ansi(BANNER_COLORS.accent, inner)}\x1b[0m${ansi(BANNER_COLORS.accent, "│")}`,
    ansi(BANNER_COLORS.accent, `╰${"─".repeat(inner.length)}╯`),
  ];
};
